// Initialize language on page load
document.addEventListener('DOMContentLoaded', () => {
    const savedLanguage = localStorage.getItem('preferredLanguage') || 'en';
    updateLanguage(savedLanguage);
    
    // Set the dropdown to the current language
    const langSelector = document.getElementById('language-selector');
    if (langSelector) {
        langSelector.value = savedLanguage;
    }
});

// Update all elements with data-i18n attribute
function updateLanguage(lang) {
    // Validate language
    if (!translations[lang]) {
        console.warn(`Language "${lang}" not supported, falling back to English`);
        lang = 'en';
    }
    
    // Save preference to localStorage
    localStorage.setItem('preferredLanguage', lang);
    
    // Update the page language attribute
    document.documentElement.lang = lang;
    
    // Get all elements with data-i18n attribute
    const elements = document.querySelectorAll('[data-i18n]');
    
    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang][key]) {
            // Check if we should set text content or value attribute
            if (element.tagName === 'INPUT' || element.tagName === 'BUTTON' || element.tagName === 'TEXTAREA') {
                // For input buttons, use placeholder or value
                if (element.hasAttribute('placeholder')) {
                    element.setAttribute('placeholder', translations[lang][key]);
                } else if (element.value !== undefined) {
                    element.value = translations[lang][key];
                } else {
                    element.textContent = translations[lang][key];
                }
            } else {
                // For regular elements, update text content
                element.textContent = translations[lang][key];
            }
        } else {
            console.warn(`Translation key "${key}" not found for language "${lang}"`);
        }
    });
    
    // Trigger custom event for any other scripts that need to know about language change
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));
}

// Make functions globally available
window.updateLanguage = updateLanguage;
window.translations = translations;
